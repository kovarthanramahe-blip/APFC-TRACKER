import type { PYQ, PYQVerificationStatus, SubjectColorKey } from '../lib/types';

let counter = 0;

function pyq(
  year: number,
  subject: SubjectColorKey,
  topicId: string,
  question: string,
  options: string[],
  correctIndex: number,
  explanation: string,
  verificationStatus: PYQVerificationStatus,
  extra?: { subtopic?: string; verificationNote?: string; source?: string },
): PYQ {
  counter += 1;
  const id = `pyq-${counter}`;
  const opts = options.map((text, i) => ({ id: `${id}-o${i}`, text }));
  return {
    id,
    year,
    subject,
    topicId,
    question,
    options: opts,
    correctOptionId: opts[correctIndex].id,
    explanation,
    verificationStatus,
    ...extra,
  };
}

